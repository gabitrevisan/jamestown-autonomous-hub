CREATE TABLE FACT_JAMESTOWN_DATA (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp TIMESTAMP NOT NULL,
    module_id VARCHAR2(10),
    ph NUMBER(4,2),
    humidity NUMBER(5,2),
    co2 NUMBER(6,2),
    temperature NUMBER(4,2),
    radiation NUMBER(5,2),
    predicted_class NUMBER(2),
    nasa_alert NUMBER(1)
);

